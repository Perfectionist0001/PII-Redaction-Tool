"""Candidate annotation generator for human review and ground-truth evaluation."""

import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Tuple

from src.config import settings
from src.detection_pipeline import create_default_pipeline
from src.extractors.docx_extractor import DOCXExtractor
from src.models import PIIEntity, TextChunk


def extract_surrounding_context(text: str, start: int, end: int, window: int = 40) -> str:
    """Extract a snippet of text surrounding the entity span for context review."""
    ctx_start = max(0, start - window)
    ctx_end = min(len(text), end + window)

    prefix = "..." if ctx_start > 0 else ""
    suffix = "..." if ctx_end < len(text) else ""

    snippet = text[ctx_start:ctx_end].replace("\n", " ").replace("\r", " ")
    return f"{prefix}{snippet}{suffix}"


def generate_candidate_annotations(
    input_docx: Path,
    json_output_path: Path,
    md_output_path: Path,
) -> Tuple[Dict[str, int], int]:
    """Run detection pipeline, collect candidate annotations with context, and save JSON and MD reports."""
    print(f"Extracting chunks from: {input_docx.name}")
    extractor = DOCXExtractor(input_docx)
    chunks = extractor.extract_chunks(include_empty=False)

    print("Running detection pipeline and resolving overlapping spans...")
    pipeline = create_default_pipeline()

    candidates_list: List[Dict[str, Any]] = []
    category_counts: Dict[str, int] = defaultdict(int)

    candidate_counter = 1

    for chunk in chunks:
        chunk_entities: List[PIIEntity] = pipeline.process_chunk(chunk)

        for entity in chunk_entities:
            category_counts[entity.entity_type] += 1

            context_str = extract_surrounding_context(
                chunk.text, entity.start, entity.end, window=40
            )

            loc_dict = {}
            if entity.source_location:
                loc = entity.source_location
                loc_dict = {
                    "source_type": loc.source_type.value,
                    "paragraph_index": loc.paragraph_index,
                    "table_index": loc.table_index,
                    "row_index": loc.row_index,
                    "cell_index": loc.cell_index,
                    "header_index": loc.header_index,
                    "footer_index": loc.footer_index,
                }

            cand_data = {
                "candidate_id": f"cand_{candidate_counter}",
                "entity_type": entity.entity_type,
                "original_text": entity.original_text,
                "start": entity.start,
                "end": entity.end,
                "confidence": round(entity.confidence, 2),
                "detector": entity.detector,
                "source_location": loc_dict,
                "surrounding_context": context_str,
            }

            candidates_list.append(cand_data)
            candidate_counter += 1

    total_candidates = len(candidates_list)

    # All expected entity categories
    ALL_CATEGORIES = sorted(
        list(
            set(
                [
                    "PERSON",
                    "EMAIL",
                    "PHONE",
                    "ORGANIZATION",
                    "ADDRESS",
                    "SSN",
                    "CREDIT_CARD",
                    "DOB",
                    "IP_ADDRESS",
                ]
                + list(category_counts.keys())
            )
        )
    )

    for cat in ALL_CATEGORIES:
        if cat not in category_counts:
            category_counts[cat] = 0

    # 1. Save candidate_annotations.json
    json_data = {
        "document_name": input_docx.name,
        "total_candidates": total_candidates,
        "summary_by_category": dict(category_counts),
        "candidates": candidates_list,
    }

    json_output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(json_output_path, "w", encoding="utf-8") as f:
        json.dump(json_data, f, indent=2, ensure_ascii=False)
    print(f"Saved JSON candidates report to: {json_output_path.resolve()}")

    # 2. Save candidate_annotations.md
    md_lines: List[str] = []
    md_lines.append("# Evaluation Candidate Annotations Report")
    md_lines.append("")
    md_lines.append("## Document Summary")
    md_lines.append(f"* **Source Document**: `{input_docx.name}`")
    md_lines.append(f"* **Total Candidates Detected**: `{total_candidates:,}`")
    md_lines.append(
        "* **IMPORTANT**: This file contains **automated candidate data** generated by the detection pipeline. "
        "It is **not** ground truth. Human auditors must review candidates to filter false positives before establishing final evaluation benchmarks."
    )
    md_lines.append("")
    md_lines.append("---")
    md_lines.append("")
    md_lines.append("## Category Candidate Counts & Risk Profiles")
    md_lines.append("")
    md_lines.append(
        "| PII Category | Candidates Detected | Status | False Positive Risk Vectors |"
    )
    md_lines.append(
        "| :--- | :--- | :--- | :--- |"
    )

    risk_descriptors = {
        "ADDRESS": "Potential inclusion of general non-address company locations",
        "CREDIT_CARD": "No candidates found; 16-digit financial figures rejected by Luhn",
        "DOB": "No candidates found; filing/incorporation dates excluded by context",
        "EMAIL": "High precision corporate and contact email addresses",
        "IP_ADDRESS": "No candidates found; IPv4 addresses absent in prospectus",
        "ORGANIZATION": "Public regulatory bodies, stock exchanges, statutory authorities",
        "PERSON": "Capitalized section titles or legal multi-word phrases",
        "PHONE": "High precision formatted Indian mobile & landline numbers",
        "SSN": "No candidates found; US SSNs absent in Indian prospectus",
    }

    for cat in ALL_CATEGORIES:
        cnt = category_counts.get(cat, 0)
        status = "Observed" if cnt > 0 else "Not Observed"
        risk = risk_descriptors.get(cat, "Standard detection risks")
        md_lines.append(f"| **{cat}** | `{cnt:,}` | {status} | {risk} |")

    md_lines.append("")
    md_lines.append("---")
    md_lines.append("")
    md_lines.append("## Detailed Candidates Grouped by Category")
    md_lines.append("")

    # Group candidates by category using defaultdict
    by_cat: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for cand in candidates_list:
        by_cat[cand["entity_type"]].append(cand)

    for cat in ALL_CATEGORIES:
        cands = by_cat[cat]
        md_lines.append(f"### {cat} ({len(cands):,} Candidates)")
        md_lines.append("")

        if not cands:
            md_lines.append(
                f"_No candidate entities of type `{cat}` were detected in `{input_docx.name}`._"
            )
            md_lines.append("")
            continue

        md_lines.append(
            "| Audit | ID | Candidate Text | Detector | Conf. | Source Location | Surrounding Context |"
        )
        md_lines.append(
            "| :---: | :--- | :--- | :--- | :---: | :--- | :--- |"
        )

        # Show representative samples (up to 100 per category for markdown readability)
        sample_limit = 100
        for cand in cands[:sample_limit]:
            cid = cand["candidate_id"]
            text_esc = cand["original_text"].replace("|", "\\|").replace("\n", " ")
            det = cand["detector"]
            conf = cand["confidence"]

            loc_parts = []
            sl = cand["source_location"]
            if sl.get("source_type"):
                loc_parts.append(sl["source_type"])
            if sl.get("paragraph_index") is not None:
                loc_parts.append(f"p:{sl['paragraph_index']}")
            if sl.get("table_index") is not None:
                loc_parts.append(f"t:{sl['table_index']} r:{sl['row_index']} c:{sl['cell_index']}")

            loc_str = " ".join(loc_parts)
            ctx_esc = cand["surrounding_context"].replace("|", "\\|").replace("\n", " ")

            md_lines.append(
                f"| [ ] | `{cid}` | `{text_esc}` | `{det}` | `{conf}` | `{loc_str}` | `{ctx_esc}` |"
            )

        if len(cands) > sample_limit:
            md_lines.append("")
            md_lines.append(
                f"_Note: Showing first {sample_limit} of {len(cands):,} candidates in Markdown report. "
                f"Complete candidate list is available in `candidate_annotations.json`._"
            )

        md_lines.append("")

    with open(md_output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))
    print(f"Saved Markdown candidate report to: {md_output_path.resolve()}")

    return category_counts, total_candidates


if __name__ == "__main__":
    import sys

    docx_path = settings.primary_input_file
    json_path = settings.evaluation_dir / "candidate_annotations.json"
    md_path = settings.evaluation_dir / "candidate_annotations.md"

    generate_candidate_annotations(docx_path, json_path, md_path)
